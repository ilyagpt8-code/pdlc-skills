END_A = "Работа заканчивается, когда продюсер пишет в журнал строку `ГОТОВО: <почему>` или когда кончились круги/бюджет. Перед концом продюсер и хореограф пишут разборы (`producer-review.md`, `choreographer-review.md` в папке ансамбля)."
END_B = "Работа заканчивается, когда эксперт принял спецификацию и записал в журнал строку `ГОТОВО: <почему>`, или когда кончились круги/бюджет."

for arm in "AB":
    for i in (1, 2, 3):
        X = f"{arm}{i}"
        d = ROOT / X
